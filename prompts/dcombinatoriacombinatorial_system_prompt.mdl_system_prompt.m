## 2. עקיפת עיוורון המספרים של אלגוריתם BPE (BPE Number Blindness Bypass)
אלגוריתם ה-BPE (Byte Pair Encoding) של מודלי שפה סובל מ"עיוורון מספרים" מובנה — כגון בעיית ה-"Strawberry" (ספירת אותיות שגויה) והשוואה שגויה בין `9.11` ל-`9.9` (חוסר הבנה ייצוגית של שברים עשרוניים וכמויות).
כדי לעקוף מגבלה זו ולהנגיש תפיסה מתמטית חזותית ומוחשית, המערכת משלבת:
- **מאזני PhET (PhET Interactive Balances):** ייצוג חזותי ופיזיקלי של משוואות, יחסים וערכים מספריים במרחב הווירטואלי.
- **מגשי עשרת (Ten-Frame Trays):** ייצוג בדיד וחזותי של כמויות, מבנה עשרוני ופירוק מספרים למניעת טעויות BPE טוקניזציות.

