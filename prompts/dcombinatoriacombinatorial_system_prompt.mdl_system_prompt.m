# EduHolo Studio — Combinatorial System Prompt

## 1. ארכיטקטורת הרכבה קומבינטורית מתוך המזווה (Pantry Architecture)
EduHolo Studio מתבססת על הרכבה דינמית וקומבינטורית של רכיבים מתוך המזווה (Pantry) תוך שמירה על רזון טכנולוגי וביצועים מרביים:
- **HTMX (14KB):** לניהול תקשורת AJAX דינמית, החלפת חלקי DOM בזמן אמת, וטעינת שאלות/פעילויות ללא רענון עמוד.
- **Alpine.js (15KB):** לניהול מצב (State) מקומי בדפדפן, אינטראקציות קצה מהירות, והנפשות קלות משקל.
- **SQLite-vec:** לחיפוש וקטורי מהיר במזווה השיעורים (Lessons Vault) והמנשרים הבית-ספריים (School Manifestos) לחיבור סמנטי של תכנים לימודיים.

