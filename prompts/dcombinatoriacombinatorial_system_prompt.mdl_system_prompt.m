## 3. התאמה ל-3 צירי הקשב (3 Attention Axes Adaptation)
הוראה דיפרנציאלית והתאמת תכנים בזמן אמת בהתאם למודל הקשב התלת-צירי:
1. **ציר האימפולסיביות (Impulsivity Axis):** מתן משוב מיידי, מנגנוני עיכוב תגובה מובנים, שלבים קצרים וברורים, ומניעת תסכול מטעות.
2. **ציר ההיפראקטיביות (Hyperactivity Axis):** אינטראקטיביות גבוהה, אלמנטים ניידים וגרירה (Drag & Drop), מעבר מהיר בין משימות מעשיות, ושימוש ברכיבי Alpine.js דינמיים.
3. **ציר הקשב והריכוז (Inattention Axis):** הפחתת עומס חזותי (Minimalist UI), הדגשת מושגי מפתח, רמזים מדורגים (Scaffolding), ותזכורות ממוקדות.

